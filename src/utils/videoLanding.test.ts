import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const videoHtmlPath = path.resolve(import.meta.dirname, '../../public/video.html');

test('public/video.html exists, is under 3 MB, has no external CDNs, and preserves @media print', () => {
  const html = fs.readFileSync(videoHtmlPath, 'utf-8');
  const sizeBytes = Buffer.byteLength(html, 'utf-8');

  assert.ok(sizeBytes < 3 * 1024 * 1024, `Expected < 3 MB, got ${sizeBytes} bytes`);
  assert.ok(html.includes('@media print'), 'Expected @media print rules');
  assert.ok(html.includes('@media (max-width: 860px)'), 'Expected mobile hero hide breakpoint');
  assert.ok(!html.includes('fonts.googleapis.com'), 'Must not load external Google Fonts');
  assert.ok(!html.includes('cdn.tailwindcss.com'), 'Must not use Tailwind CDN');
});

